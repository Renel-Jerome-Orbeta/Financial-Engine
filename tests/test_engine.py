from pathlib import Path
import pytest
import polars as pl
from engine.backtester import VectorizedBacktester

# Path to the sample market data file used for testing
PARQUET_PATH = Path("./data/aapl_daily.parquet")


def test_backtester_initialization():
    """
    Verifies that the VectorizedBacktester initializes correctly with 
    default institutional parameters (capital, fee rate, slippage rate).
    """
    engine = VectorizedBacktester(parquet_path=PARQUET_PATH)
    assert engine.initial_capital == 100000.0
    assert engine.fee_rate == 0.0005
    assert engine.slippage_rate == 0.0001


def test_run_strategy_output_structure():
    """
    Verifies that `run_strategy()` processes data correctly and returns 
    a Polars DataFrame containing all mandatory analytical columns.
    """
    if not PARQUET_PATH.exists():
        pytest.skip("Parquet data file not found. Skipping engine test.")

    engine = VectorizedBacktester(parquet_path=PARQUET_PATH)
    df_results = engine.run_strategy(fast_span=50, slow_span=200)

    # Validate that output is a Polars DataFrame
    assert isinstance(df_results, pl.DataFrame)
    
    # Check for mandatory schema columns generated by the backtest pipeline
    expected_columns = [
        "timestamp", "close", "ema_fast", "ema_slow", 
        "position", "trade_executed", "net_strategy_return", "portfolio_value_net"
    ]
    for col in expected_columns:
        assert col in df_results.columns


def test_compute_metrics_keys():
    """
    Verifies that `compute_metrics()` computes and returns all required 
    institutional performance metric keys with correct data types.
    """
    if not PARQUET_PATH.exists():
        pytest.skip("Parquet data file not found. Skipping metrics test.")

    engine = VectorizedBacktester(parquet_path=PARQUET_PATH)
    df_results = engine.run_strategy(fast_span=50, slow_span=200)
    metrics = engine.compute_metrics(df_results)

    expected_keys = [
        "Starting Capital",
        "Ending Portfolio Value",
        "Total Return (%)",
        "CAGR (%)",
        "Annualized Volatility (%)",
        "Sharpe Ratio",
        "Maximum Drawdown (%)"
    ]
    for key in expected_keys:
        assert key in metrics
        assert isinstance(metrics[key], float)